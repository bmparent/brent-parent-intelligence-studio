import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PG_BASE_URL || 'http://127.0.0.1:4173';
const evidence = process.env.PG_EVIDENCE_DIR || '/tmp/eidos-candlelight';
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch(process.env.PLAYWRIGHT_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE } : {});
try {
  for (const width of [1440, 768, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = [], commerceRequests = [];
    page.on('pageerror', error => { const message = `${page.url()}: ${error.message}`; errors.push(message); console.error(message); });
    page.on('console', message => { if (message.type() === 'error') console.error(`${page.url()}: ${message.text()}`); });
    page.on('request', request => { if (/stores\.inksoft\.com/.test(request.url())) commerceRequests.push(request.url()); });
    try {
      await page.goto(base + '/work/');
      const consent = page.getByRole('button', { name: 'Essential only', exact: true });
      if (await consent.isVisible()) await consent.click();
      const gallery = page.locator('#site-gallery');
      await gallery.getByRole('button', { name: 'Storefronts', exact: true }).click();
      await gallery.getByRole('searchbox').fill('candlelight');
      assert.equal(await gallery.locator('.ew-site-card').count(), 1);
      await gallery.locator('.ew-site-card').screenshot({ path: path.join(evidence, `candlelight-gallery-${width}.png`) });
      await gallery.getByRole('link', { name: 'Explore full storefront', exact: false }).click();
      await page.waitForURL(/\/work\/candlelight-exclusive\/?$/);
      const root = page.locator('#clex-demo');
      assert.equal(await root.count(), 1);
      assert.equal(await page.locator('h1').count(), 1);
      await root.locator('.clex-feature img').evaluate(image => image.decode());
      assert.equal(await root.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(245, 241, 233)');
      assert.equal(await root.locator('.clex-feature').evaluate(el => getComputedStyle(el, '::before').animationName), 'none', 'reduced motion stops flicker');
      await page.locator('.clex-demo-shell').screenshot({ path: path.join(evidence, `candlelight-home-${width}.png`) });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'homepage fits viewport');
      await root.getByRole('button', { name: 'Explore the collection', exact: true }).click();
      assert.equal(await root.locator('.clex-product').count(), 2);
      assert.equal(await root.getByRole('heading', { name: 'Choose your fit.', exact: true }).evaluate(el => el === document.activeElement), true);
      await root.getByRole('button', { name: 'Shop men’s', exact: true }).click();
      await root.getByRole('button', { name: 'Back', exact: true }).click();
      assert.match(await root.locator('.clex-detail-grid img').first().getAttribute('src'), /men-back/);
      await root.getByRole('button', { name: 'Front', exact: true }).click();
      await root.locator('summary').click();
      await root.locator('.clex-size-guide img').evaluate(image => image.decode());
      assert.equal(await root.locator('.clex-size-guide img').evaluate(image => image.naturalWidth), 1600);
      await root.getByLabel('Size', { exact: true }).selectOption('2XL');
      await root.getByRole('checkbox').check();
      await root.getByLabel('Name, title, or position').fill('   ');
      await root.getByRole('button', { name: 'Add to demo bag', exact: false }).click();
      assert.equal(await root.locator('.clex-form').count(), 1, 'blank personalization rejected');
      await root.getByLabel('Name, title, or position').fill('Sample Performer');
      await root.getByRole('button', { name: 'Add to demo bag', exact: false }).click();
      assert.match(await root.locator('.clex-bag-items').innerText(), /Sample Performer/);
      assert.match(await root.locator('.clex-bag-total').innerText(), /\$101\.00/);
      await root.getByRole('button', { name: 'Back to the collection', exact: false }).click();
      await root.getByRole('button', { name: 'Shop women’s', exact: true }).click();
      await root.getByLabel('Size', { exact: true }).selectOption('3XL');
      await root.getByLabel('Quantity', { exact: true }).fill('2');
      await root.locator('summary').click();
      assert.match(await root.locator('.clex-size-guide img').getAttribute('src'), /women-size-guide/);
      await root.locator('.clex-size-guide img').evaluate(image => image.decode());
      await root.screenshot({ path: path.join(evidence, `candlelight-product-${width}.png`) });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'product fits viewport');
      await root.getByRole('button', { name: 'Add to demo bag', exact: false }).click();
      assert.match(await root.locator('.clex-bag-total').innerText(), /\$281\.00/);
      assert.equal(await root.locator('.clex-bag-items li').count(), 2);
      await root.getByRole('button', { name: 'Remove men’s 2XL jacket', exact: true }).click();
      assert.match(await root.locator('.clex-bag-total').innerText(), /\$180\.00/);
      await root.getByRole('button', { name: 'Remove women’s 3XL jacket', exact: true }).click();
      assert.match(await root.locator('.clex-empty').innerText(), /empty/);
      await root.getByRole('button', { name: 'Home', exact: true }).click();
      await page.getByRole('button', { name: 'Pause lighting', exact: true }).click();
      assert.equal(await root.getAttribute('data-lighting-paused'), 'true');
      await page.getByRole('button', { name: 'Resume lighting', exact: true }).click();
      await page.reload();
      assert.match(await root.locator('.clex-bag-link').innerText(), /\(0\)/);
      await page.goto(base + '/');
      assert.equal(await page.locator('#site-gallery .ew-site-card').first().getByRole('heading', { name: 'Candlelight Exclusive', exact: true }).count(), 1);
      assert.deepEqual(errors, []);
      assert.deepEqual(commerceRequests, [], 'demo never contacts the live catalog');
      console.log(`PASS Candlelight ${width}px: gallery, full homepage, two fits, back/front, guides, options, totals, removal, focus, pause and motion preference`);
    } finally { await context.close(); }
  }
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const page = await context.newPage();
  await page.goto(base + '/work/candlelight-exclusive');
  const feature = page.locator('.clex-feature');
  await feature.scrollIntoViewIfNeeded();
  await page.waitForFunction(() => document.querySelector('#clex-demo').dataset.lightingVisible === 'true');
  assert.equal(await feature.evaluate(el => getComputedStyle(el, '::before').animationPlayState), 'running');
  const glow = await feature.evaluate(el => getComputedStyle(el).backgroundImage);
  const before = await feature.evaluate(el => getComputedStyle(el, '::before').opacity);
  await page.waitForTimeout(700);
  assert.notEqual(await feature.evaluate(el => getComputedStyle(el, '::before').opacity), before, 'living light changes opacity');
  await page.getByRole('button', { name: 'Pause lighting', exact: true }).click();
  assert.equal(await feature.evaluate(el => getComputedStyle(el, '::before').animationPlayState), 'paused');
  assert.equal(await feature.evaluate(el => getComputedStyle(el).backgroundImage), glow, 'pausing retains original static amber glow');
  console.log('PASS active flicker and static-glow pause');
  await context.close();
} finally { await browser.close(); }
